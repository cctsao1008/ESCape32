#!/usr/bin/env python3
"""Compile AM13E IO-only auxiliary feature profile and reject pin conflicts.

Option 1 PB13/PA22 and the selected native resources are allocated
by the default Reference firmware. Optional OC, Serial TX and Current
Sense PINCM values in this test are SYNTHETIC, NOT a proposed PCB.
No file generated by this smoke is flashed.
"""
import json
import pathlib
import shlex
import subprocess
import sys

if len(sys.argv)!=2:
    raise SystemExit("usage: board_profile_compile_smoke.py BUILD_DIRECTORY")
build=pathlib.Path(sys.argv[1])
commands=json.loads((build/"compile_commands.json").read_text())

targets={"motor_safety.c","motor_power_stage.c","motor_runtime_irq.c",
         "analog_runtime.c","main.c","util.c","fault_input.c",
         "irq_vectors.c","serial_uart_rx.c","motor_fault_route.c"}
observed={}

def syntax_check(obj,flags,should_pass=True,expected_error=None):
    args=shlex.split(obj["command"])
    stripped=[]
    skip=False
    for word in args:
        if skip:
            skip=False
            continue
        if word=="-o":
            skip=True
            continue
        if word=="-c":
            continue
        stripped.append(word)
    run=subprocess.run(stripped+flags+["-Werror","-fsyntax-only"],
                       cwd=obj["directory"],capture_output=True,text=True,
                       check=False)
    if bool(run.returncode==0)!=should_pass or (
        expected_error and expected_error not in run.stderr):
        print(run.stdout+run.stderr)
        raise SystemExit("Unexpected IO-only compile result for "+
                         pathlib.Path(obj["file"]).name+
                         ": "+str(flags))
    return run

for obj in commands:
    path=pathlib.Path(obj["file"])
    if path.name not in targets or "CMakeFiles/AM13E-rev17.3.elf.dir/" not in obj["command"]:
        continue
    observed[path.name]=obj
    syntax_check(obj,[])
    print("PASS: default IO-only "+path.name)

if set(observed)!=targets:
    raise SystemExit("Missing reference FW1 sources "+str(targets-set(observed)))

# Exercise only physical pad-mode selection; never enable peripherals or
# use a synthetic PINCM number as an on-board design recommendation.
optional=[
    "-DAM13E_BOARD_OC_GPIO_PINCM=48",
    "-DAM13E_BOARD_SERIAL_TX_PINCM=49",
    "-DAM13E_BOARD_CURRENT_SENSE_PINCM=50"
]
syntax_check(observed["fault_input.c"],optional)
print("PASS: optional OC/Serial TX/Current pin modes compile")

syntax_check(observed["fault_input.c"],
             ["-DAM13E_BOARD_OC_GPIO_PINCM=47"],
             False,"Aux IO reservation conflicts")
syntax_check(observed["fault_input.c"],
             ["-DAM13E_BOARD_SERIAL_TX_PINCM=49",
              "-DAM13E_BOARD_CURRENT_SENSE_PINCM=49"],
             False,"Aux IO reservations must use distinct pins")
print("PASS: overlapping and reserved pin mappings rejected")

# Conditional Analog Receiver: positive compile is ONLY a synthetic
# source fixture. No pin/channel here is approved for a physical PCB.
receiver_flags=[
    "-DAM13E_BOARD_SENSORS_CONFIGURED=1",
    "-DAM13E_BOARD_ADC_FULLSCALE=4095", "-DAM13E_BOARD_ADC_VREF_MV=3300",
    "-DAM13E_BOARD_NTC_SUPPLY_MV=3300", "-DAM13E_BOARD_VBUS_TOP_OHMS=26820",
    "-DAM13E_BOARD_VBUS_BOTTOM_OHMS=1000", "-DAM13E_BOARD_NTC_MODEL=3",
    "-DANALOG_CHAN=1",
    "-DAM13E_BOARD_ANALOG_INPUT_PINCM=50",
    "-DAM13E_BOARD_ANALOG_INPUT_CHANNEL=7",
    "-DAM13E_BOARD_ANALOG_INPUT_FULLSCALE=4095",
    "-DAM13E_BOARD_ANALOG_INPUT_VREF_MV=3300"
]
syntax_check(observed["analog_runtime.c"],receiver_flags)
syntax_check(observed["analog_runtime.c"],["-DANALOG_CHAN=1"],
             False,"Analog input_mode=1 requires board-supplied")
syntax_check(observed["analog_runtime.c"],
             [f for f in receiver_flags
              if not f.startswith("-DAM13E_BOARD_ANALOG_INPUT_PINCM")] +
             ["-DAM13E_BOARD_ANALOG_INPUT_PINCM=26"],
             False,"Analog receiver conflicts")
print("PASS: conditional Analog input_mode=1 ADC0 SOC3 build and board pin guards")

# Explicit hardware routing requirements; the positive profile is a
# synthetic compile fixture, not an actual valid UC-to-pin assignment.
uart=["-DAM13E_BOARD_SERIAL_RX_CONFIGURED=1",
      "-DAM13E_BOARD_SERIAL_RX_UC_INDEX=0",
      "-DAM13E_BOARD_SERIAL_RX_PINCM=50",
      "-DAM13E_BOARD_SERIAL_RX_PIN_FUNCTION=2",
      "-DAM13E_BOARD_SERIAL_RX_BUSCLK_HZ=100000000",
      "-DAM13E_BOARD_SERIAL_SBUS_PIN_INVERT=1"]
syntax_check(observed["serial_uart_rx.c"],uart)
syntax_check(observed["serial_uart_rx.c"],
             ["-DAM13E_BOARD_SERIAL_RX_CONFIGURED=1"],
             False,"Board UART RX requires dedicated UC")
syntax_check(observed["serial_uart_rx.c"],
             [x for x in uart if not x.startswith("-DAM13E_BOARD_SERIAL_RX_PINCM")] +
             ["-DAM13E_BOARD_SERIAL_RX_PINCM=46"],
             False,"Native serial RX pin conflicts")
syntax_check(observed["serial_uart_rx.c"],
             [x for x in uart if not x.startswith("-DAM13E_BOARD_SERIAL_RX_UC_INDEX")] +
             ["-DAM13E_BOARD_SERIAL_RX_UC_INDEX=6"],
             False,"Select AM13E UNICOMM0..UNICOMM5")
print("PASS: native UNICOMM RX IRQ/FIFO selected-profile syntax and safety guards")
# Real Option 1 UC1 route, distinct from command UC0/UC3; baud is a fixture.
syntax_check(observed["serial_uart_rx.c"],["-DAM13E_BOARD_DEBUG_UART_BAUD=115200"])
syntax_check(observed["serial_uart_rx.c"],["-DAM13E_BOARD_DEBUG_UART_BAUD=0"],
             False,"Debug baud requires representable")
syntax_check(observed["serial_uart_rx.c"],
             ["-DAM13E_BOARD_DEBUG_UART_BAUD=115200", "-DAM13E_BOARD_TELEM_UC_INDEX=1"],
             False,"debug UC1 cannot share")
print("PASS: Option 1 UC1 debug routing and baud/ownership guards")
oc=["-DAM13E_OC_U_DAC_CODE=2048", "-DAM13E_OC_V_DAC_CODE=2048",
    "-DAM13E_OC_W_DAC_CODE=2048", "-DAM13E_OC_U_INVERT=0",
    "-DAM13E_OC_V_INVERT=0", "-DAM13E_OC_W_INVERT=0"]
syntax_check(observed["motor_fault_route.c"],oc)
syntax_check(observed["motor_fault_route.c"],oc+["-UAM13E_OC_U_INVERT"],
             False,"requires all three explicit")
syntax_check(observed["motor_fault_route.c"],
             oc+["-UAM13E_OC_U_DAC_CODE", "-DAM13E_OC_U_DAC_CODE=4096"],
             False,"Invalid Option 1 OC")
syntax_check(observed["motor_fault_route.c"],
             oc+["-UAM13E_OC_V_INVERT", "-DAM13E_OC_V_INVERT=2"],
             False,"Invalid Option 1 OC")
print("PASS: Option 1 overcurrent completeness/code/polarity compile guards")


# TX-positive case remains a COMPILE-ONLY synthetic fixture.
tx=uart+["-DAM13E_BOARD_SERIAL_TX_CONFIGURED=1",
         "-DAM13E_BOARD_SERIAL_TX_PINCM=51",
         "-DAM13E_BOARD_SERIAL_TX_PIN_FUNCTION=2",
         "-DAM13E_BOARD_SERIAL_TX_TWO_WIRE=1"]
syntax_check(observed["serial_uart_rx.c"],tx)
syntax_check(observed["serial_uart_rx.c"],
             [x for x in tx if not x.startswith("-DAM13E_BOARD_SERIAL_TX_TWO_WIRE")],
             False,"UART TX requires explicit TX")
syntax_check(observed["serial_uart_rx.c"],
             [x for x in tx if not x.startswith("-DAM13E_BOARD_SERIAL_TX_PINCM")] +
             ["-DAM13E_BOARD_SERIAL_TX_PINCM=50"],
             False,"CRSF TX must own a distinct")
print("PASS: optional CRSF TX IRQ/EOT board route and fail-closed contract")
# Real device functions, compile-only routing checks; waveform needs hardware.
for uc,rxpf,txpf in [(0,8,9),(3,11,10)]:
    pa26=[x for x in tx if not any(x.startswith(k) for k in [
        "-DAM13E_BOARD_SERIAL_RX_UC_INDEX", "-DAM13E_BOARD_SERIAL_RX_PINCM",
        "-DAM13E_BOARD_SERIAL_RX_PIN_FUNCTION", "-DAM13E_BOARD_SERIAL_TX_PINCM",
        "-DAM13E_BOARD_SERIAL_TX_PIN_FUNCTION", "-DAM13E_BOARD_SERIAL_TX_TWO_WIRE"])] + [
        f"-DAM13E_BOARD_SERIAL_RX_UC_INDEX={uc}", "-DAM13E_BOARD_SERIAL_RX_PINCM=26",
        f"-DAM13E_BOARD_SERIAL_RX_PIN_FUNCTION={rxpf}", "-DAM13E_BOARD_SERIAL_TX_PINCM=26",
        f"-DAM13E_BOARD_SERIAL_TX_PIN_FUNCTION={txpf}", "-DAM13E_BOARD_SERIAL_TX_TWO_WIRE=0"]
    syntax_check(observed["serial_uart_rx.c"],pa26)
    syntax_check(observed["serial_uart_rx.c"],
        [x for x in pa26 if not x.startswith("-DAM13E_BOARD_SERIAL_TX_PIN_FUNCTION")]+[
            "-DAM13E_BOARD_SERIAL_TX_PIN_FUNCTION=2"],False,"Single-wire command UART requires actual")
print("PASS: PA26 UC0/UC3 native single-pad route and wrong-function rejection")


# Verify the preprocessed default firmware, rather than banning the
# configured production implementation from the same source file.
source_root=pathlib.Path(__file__).resolve().parents[4]
power=(source_root/"mcu/AM13E/hal/motor_power_stage.c").read_text()
nfault=(source_root/"mcu/AM13E/hal/fault_input.c").read_text()
runtime=(source_root/"mcu/AM13E/hal/motor_safety.c").read_text()
vectors=(source_root/"mcu/AM13E/hal/irq_vectors.c").read_text()
ref_cmake=(source_root/"CMakeLists.txt").read_text()
def default_preprocessed(name):
    args=shlex.split(observed[name]["command"])
    out=[]
    skip=False
    for word in args:
        if skip:
            skip=False
            continue
        if word=="-o":
            skip=True
        elif word!="-c":
            out.append(word)
    return subprocess.run(out+["-E","-P"],cwd=observed[name]["directory"],
                          capture_output=True,text=True,check=True).stdout
power_default=default_preprocessed("motor_power_stage.c")
runtime_default=default_preprocessed("motor_safety.c")
checks=[
    ("PB13 active enable", "gate_hold_inactive" in power and
     "int am13e_power_stage_enable(void)" not in power_default and
     "am13e_motor_output_start()" not in runtime_default),
    ("nFAULT IRQ", "DL_GPIO_enableInterrupt(" not in nfault and
     "am13e_app_nfault_asserted(" not in vectors),
    ("Fault Trip", "am13e_app_motor_nfault_trip_init();" not in runtime_default),
    ("Independent OC", "DL_XBAR_selectPWMXBARSource(" not in power),
    ("GPIO-only serial", "DL_GPIO_initDigitalInput(AM13E_BOARD_SERIAL_TX_PINCM)" in nfault),
    ("Analog-only current sense", "DL_GPIO_initPeripheralAnalogFunction(AM13E_BOARD_CURRENT_SENSE_PINCM)" in nfault)
]
for name,passed in checks:
    if not passed:
        raise SystemExit("IO-only non-operation contract failed: "+name)
    print("PASS: "+name+" IO-only")

for flag in ["-DAM13E_COMMAND_PINCM=14", "-DAM13E_IO_TIMER_INDEX=12",
             "-DAM13E_IO_DMA_CHANNEL=1", "-DAM13E_IO_CAPTURE_CHANNEL=1"]:
    syntax_check(observed["main.c"],[flag],False)
print("PASS: incompatible command pin/timer/capture/DMA combinations rejected")
