#!/usr/bin/env python3
"""Compile AM13E IO-only auxiliary feature profile and reject pin conflicts.

Option 1 PB13/PA22 and the selected native resources are allocated
by the default Reference firmware. Optional OC, Serial TX and Current
Sense PINCM values in this test are SYNTHETIC, NOT a proposed PCB.
No file generated by this smoke is flashed.
"""
import json
import pathlib
import shlex
import subprocess
import sys

if len(sys.argv)!=2:
    raise SystemExit("usage: board_profile_compile_smoke.py BUILD_DIRECTORY")
build=pathlib.Path(sys.argv[1])
commands=json.loads((build/"compile_commands.json").read_text())

targets={"motor_safety.c","motor_power_stage.c","motor_runtime_irq.c",
         "analog_runtime.c","main.c","util.c","fault_input.c",
         "irq_vectors.c","serial_uart_rx.c","telem_backend.c","motor_fault_route.c"}
observed={}

def syntax_check(obj,flags,should_pass=True,expected_error=None):
    args=shlex.split(obj["command"])
    stripped=[]
    skip=False
    for word in args:
        if skip:
            skip=False
            continue
        if word=="-o":
            skip=True
            continue
        if word=="-c":
            continue
        stripped.append(word)
    run=subprocess.run(stripped+["-DAM13E_BOARD_MCU_PART=23019", "-DAM13E_BOARD_PACKAGE=1"]+flags+["-Werror","-fsyntax-only"],
                       cwd=obj["directory"],capture_output=True,text=True,
                       check=False)
    if bool(run.returncode==0)!=should_pass or (
        expected_error and expected_error not in run.stderr):
        print(run.stdout+run.stderr)
        raise SystemExit("Unexpected IO-only compile result for "+
                         pathlib.Path(obj["file"]).name+
                         ": "+str(flags))
    return run

for obj in commands:
    path=pathlib.Path(obj["file"])
    if path.name not in targets or "CMakeFiles/AM13E-rev17.3.elf.dir/" not in obj["command"]:
        continue
    observed[path.name]=obj
    syntax_check(obj,[])
    print("PASS: default IO-only "+path.name)

if set(observed)!=targets:
    raise SystemExit("Missing reference FW1 sources "+str(targets-set(observed)))

